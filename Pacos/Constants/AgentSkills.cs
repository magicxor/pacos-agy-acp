                   ## B. bubbleMap — точки на карте

                   ### B1. Данные и подложка
                   dataset { outline: '<имя карты>', data: [{ longitude, latitude, value }, ...] } — подложку bubbleMap берёт из outline, а не из map. Имена фич тут ни при чём: точка ставится по координатам, в любом месте карты.
                   Размер пузыря читается ТОЛЬКО из value. Поле r из обычного bubble не работает: строка { x, y, r } встанет на своё место, но превратится в точку в 1 пиксель. Координаты клади в longitude/latitude, величину — в value.
                   Строке можно дать label — он попадёт в подпись (раздел B5).
                   Покрытие тут не считается: warnings о непокрытых фичах для bubbleMap не приходят, и это нормально — точки не обязаны закрывать всю карту.

                   ### B2. Цвет пузырей — задавай ВСЕГДА
                   Цвет пузырей задаётся ТОЛЬКО через backgroundColor в датасете, и задавать его ОБЯЗАТЕЛЬНО. Как только в датасете появляется хоть один цвет (например borderColor из раздела A2), chart.js перестаёт назначать палитру сам, и незаданная заливка падает в дефолтный серый — ровно цвет подложки. Пузыри становятся невидимыми, карта выглядит пустой.
                   options.scales.color к bubbleMap отношения не имеет: цветовая шкала пузыри не красит и легенду не рисует. Не добавляй её, весь раздел A3 сюда не переносится.
                   Рабочая пара: backgroundColor: "rgba(231,76,60,0.65)" (полупрозрачный, чтобы пересекающиеся пузыри читались) плюс borderColor: "#c0392b" и borderWidth: 1.
                   Если пузыри кодируют категорию (порты и аэропорты, разные годы), делай датасет на категорию со своим цветом и label и включай обычную легенду options.plugins.legend.

                   ### B3. Размер пузырей — шкала size
                   Радиус считает шкала size: options.scales.size = { "axis": "x", "range": [5, 34] }. axis: "x" обязателен, иначе шкала выкинет ошибку.
                   - range — минимальный и максимальный радиус В ПИКСЕЛЯХ. По умолчанию [2, 20], для карты во весь кадр это мелко; бери примерно [5, 30].
                   - Значению пропорциональна ПЛОЩАДЬ пузыря, а не радиус, поэтому вдвое большее значение выглядит примерно в 1.4 раза шире. Так и надо: глаз сравнивает площади.
                   - missing — радиус в пикселях для строк без значения (по умолчанию 1). Это НЕ цвет, в отличие от scales.color.missing из раздела A3.

                   ### B4. Легенда размеров или подписи — что-то одно
                   Шкала size по умолчанию рисует свою легенду в правом нижнем углу, и там её часто обрезает край кадра. Выбирай одно из двух:
                   - подписи вместо легенды (обычно читается лучше): scales.size.display = false, а числа печатай плагином datalabels (раздел B5);
                   - легенда размеров: scales.size = { "axis": "x", "range": [5, 30], "display": true, "ticks": { "color": "black", "font": { "size": 13 } }, "legend": { "position": "bottom-right", "align": "right", "length": 150, "width": 70 } } и ОБЯЗАТЕЛЬНО оставь поле справа: options.layout.padding = { "left": 20, "right": 80, "top": 10, "bottom": 20 }, иначе подписи обрежутся.
                   Обычную легенду датасета держи выключенной (options.plugins.legend.display = false), кроме случая с категориями из раздела B2.

                   ### B5. Подписи точек
                   Плагин datalabels для карт по умолчанию выключен, включается заданием любой его опции. Для bubbleMap подписи почти всегда нужны: по одному размеру пузыря значение не прочитать.
                   Включённый datalabels сам печатает значение, а если в строке есть label — название сверху и значение снизу. Форматер для этого НЕ НУЖЕН.
                   Если всё же пишешь свой formatter: у точки берутся v.label и v.value. Правило раздела A6 про value.feature.properties.name здесь НЕ работает — фичи у точки нет, там будет undefined.
                   Ставь подпись над пузырём, чтобы она его не закрывала: "align": "top", "offset": 4. Точек много и подписи наезжают — "display": "auto".

