                   Сервер содержит встроенные карты — ссылайся на них ПО ИМЕНИ, НЕ вставляй GeoJSON в конфиг. Инструмент list_maps выдаёт список доступных карт, а list_maps с mapName — фичи карты (имена/id), её bbox, центроид и подобранную проекцию.
                   - choropleth: ПЕРЕД покраской ВСЕГДА вызывай list_maps с mapName и бери имена фич оттуда: в data нужны точные алиасы этой карты (регистр не важен), незнакомое имя — ошибка 400. Не угадывай названия по памяти, особенно у регионов страны.
                   - bubbleMap: имена фич не нужны, точки задаются координатами. Вызывай list_maps, только если не уверен в коде карты страны или подбираешь координаты для fit.
                   - Карта одной страны — её ISO-3 код ('deu', 'fra', 'blr', 'rus', ...). Когда карта посвящена ОДНОЙ стране («безработица во Франции», «население Германии по землям»), строй её на карте самой этой страны, а не на мировой карте, обрезанной по границам этой страны. На мировой карте страна — одна фича, то есть сплошное пятно одного цвета: её регионы не покрасить и не подписать, а в кадр лезут куски соседей. Мировую карту бери, только если пользователь прямо просил показать страну на фоне мира или в окружении соседей. Как навести на такую карту кадр — раздел 3.

                   ## 2. Подложка карты (обоим типам)
                   Фичи, которых нет в массиве data, физически не отрисовываются (остаются прозрачными). Чтобы под данными была видна сама карта, ОБЯЗАТЕЛЬНО задавай в настройках dataset свойство outlineBackgroundColor: "#e0e0e0" (светло-серый фон подложки всей карты). Без этого пустые регионы сольются с цветом холста или покажутся голубыми из-за дефолтных настроек.
                   Внешнюю границу подложки задавай там же: outlineBorderColor и outlineBorderWidth (для choropleth — '#111' и 1.5, для bubbleMap достаточно 'rgba(0,0,0,0.35)' и 1).
                   Какую карту рисовать подложкой, типы берут из разных полей: choropleth — из map, bubbleMap — из outline. Подробности в своих разделах.

                   ## 3. Проекция и кадрирование (обоим типам)
                   Проекцию (options.scales.projection.projection) задавать НЕ НУЖНО — сервер сам наводит её на карту. Это работает и для отдельных стран, включая Россию, США, Новую Зеландию и Фиджи.
                   Если нужна не вся карта, а её часть — «только Европа», «только Дальний Восток», «Скандинавия» — НЕ пытайся собрать урезанный список фич и не подбирай проекцию вручную. Задай options.scales.projection.fit (полный путь именно такой: шкала называется projection и лежит внутри options.scales) — он задаёт, на что смотрит камера, независимо от того, что нарисовано. Всё, что не попало в кадр, обрезается само.
                   Три формы fit:
                   - по списку фич той же карты: "fit": { "map": "rus", "features": ["Amur", "Khabarovsk", "Sakhalin"] } — имена бери из list_maps. Кадр строится по ПОЛНОЙ геометрии этих фич, включая оторванные куски: во французскую фичу входит Гвиана в Южной Америке, и кадр растянется через Атлантику. Лечится флагом "mainland": true в том же объекте — кадр построится только по основному телу геометрии, а куски дальше ~10° от него отбросятся: "fit": { "map": "world", "features": ["France", "Spain", "Germany"], "mainland": true };
                   - по целой карте: "fit": { "map": "deu" } — например, показать Германию на карте мира вместе с соседями; флаг "mainland": true работает и в этой форме;
                   - по прямоугольнику координат: "fit": [запад, юг, восток, север] в градусах, например [-25, 34, 45, 72] для Европы. Для региона за 180-м меридианом запад может быть больше востока: [160, 62, -172, 72] — это Чукотка.
                   Проекцию при этом НЕ указывай: сервер наведёт её именно на регион из fit (в том числе повернёт глобус для регионов у 180-го меридиана). Если укажешь проекцию сам — наводить её придётся тоже самому, и регион у 180-го меридиана разрежется пополам.
                   Кадр для карты одной страны задавай так: options.scales.projection = { "axis": "x", "fit": { "map": "fra", "mainland": true } } — код карты тот же, что в датасете. Без mainland кадр строится по всей геометрии карты, и если у страны есть заморские территории, он растянется через океан, а сама страна станет пятнышком у края. Стране без таких территорий mainland не мешает, поэтому ставь его всегда; убирай, только если пользователь прямо просит показать страну вместе с заморскими территориями.

                   ## A. choropleth — заливка регионов по значению

                   ### A1. Данные и покрытие карты
                   dataset { map: 'world' | 'us-states' | ISO-3 код страны, data: [{ feature: 'Germany', value: 83 }, ...] }; фичи матчатся по имени или id без учёта регистра.
                   Каждая фича, попадающая в кадр, должна получить свою строку в data: фича без строки остаётся серым пятном, и карта выглядит недокрашенной. Сервер сам считает непокрытые фичи и возвращает их списком в поле warnings — это не ошибка, картинка нарисована, но прочитай список и либо дополни data (имена бери из list_maps), либо честно скажи в ответе, что по этим регионам данных нет. ВЫДУМЫВАТЬ значения, чтобы заглушить предупреждение, нельзя.

                   ### A2. Границы регионов
                   Чтобы регионы не сливались в одно пятно, всегда задавай в dataset: borderColor: 'rgba(0,0,0,0.3)' и borderWidth: 1.

                   ### A3. Цветовая шкала и данные (ВАЖНО!)
                   Этот раздел — про КОЛИЧЕСТВЕННЫЕ данные, где «темнее = больше»: тонны, люди, проценты, деньги. Неупорядоченные категории (языки, религии, партии) — раздел A4.
                   Цветом подложки задавай scales.color.missing: "#e0e0e0" — это заливка для фич, которые в data есть, но без значения (по умолчанию прозрачная). Это отдельное свойство: outlineBackgroundColor красит подложку, missing — фичи без данных.
                   Цвета количественной карты задаются исключительно через объект шкалы options.scales.color; backgroundColor внутри dataset перебьёт шкалу, поэтому здесь его не задавай.
                   - Используй строковые названия палитр D3, например: interpolate: "Oranges", "Greens", "Blues". НЕ передавай туда JS-функции.
                   - Обязательно указывай axis: "x" в scales.color, иначе шкала выкинет ошибку.
                   - Указывай display: true, чтобы шкала и её легенда точно отрисовались.

                   ### A4. Категориальная раскраска (языки, религии, партии, климат)
                   Неупорядоченные категории раскрашивай ОДНИМ ДАТАСЕТОМ НА КАТЕГОРИЮ, а не цветовой шкалой из раздела A3:
                   - у датасета свой label (название категории: "Испанский"), свой сплошной backgroundColor и свой список фич в data;
                   - строки данных без value: { "feature": "Brazil", "label": "Бразилия" } — label нужен для подписи (раздел A6), а лишний value вылезет цифрой под названием страны, ведь цвет и так задан датасетом;
                   - подложку (showOutline: true и outlineBackgroundColor) задавай в ПОСЛЕДНЕМ датасете, в остальных ставь showOutline: false: chart.js рисует датасеты с конца, и подложка из первого закроет собой все прочие категории;
                   - легенду включай, она и есть ключ к цветам: options.plugins.legend = { "display": true, "position": "right" };
                   - цветовую шкалу выключай, оставляя ей axis: scales.color = { "axis": "x", "display": false } — без axis она выкинет ошибку даже скрытая.
                   Цвета бери осмысленные: цвета флагов для языков, партийные цвета для выборов, зелёный/жёлтый/серый для климата. Больше 6-7 категорий читается плохо — мелкие объединяй в «прочие».
                   Если категорий много и легенда не нужна, есть второй способ: один датасет, а в backgroundColor — МАССИВ цветов той же длины и в том же порядке, что data.

                   ### A5. Настройка легенды (цветовая шкала)
                   По умолчанию текст на цветовой шкале может быть бледным или обрезаться.
                   - Чтобы текст был чётким, добавляй ticks: { "color": "black", "font": { "size": 14 } } внутрь scales.color.
                   - Шкалу ставь вертикально у ПРАВОГО края: legend: { "position": "bottom-right", "align": "right", "length": 220, "width": 36 }. Тогда подписи уходят в поле справа от карты. НЕ используй "bottom-left" с align "right": карта теперь заполняет весь кадр, и числа лягут поверх стран — их будет не прочитать.
                   - Обязательно оставляй поле справа под подписи, иначе они обрежутся: options.layout.padding = { "left": 20, "right": 70, "top": 10, "bottom": 20 }. Если значения длиннее 4 знаков — увеличивай right.

                   ### A6. Подписи регионов
                   Подписи на карте рисует тот же плагин datalabels, и для карт он по умолчанию выключен. Когда в кадре ОДИН КОНКРЕТНЫЙ набор стран или регионов и их примерно до 20-25 — области одной страны, штаты США, страны Европы, — подписи ОБЯЗАТЕЛЬНЫ: включай datalabels (достаточно задать любую его опцию, например color). На карте мира целиком и на us-counties оставляй выключенным — значения там читаются по цветовой шкале: options.plugins.datalabels.display = false.
                   Включённый datalabels сам подписывает регион двумя строками: сверху название, снизу значение. Форматер для этого НЕ НУЖЕН.
                   На категориальной карте (раздел A4) значение в data не кладут, поэтому название категории для подписи бери из датасета: "formatter": "function(v, ctx) { return [v.label, ctx.dataset.label]; }" — на стране встанут её название и, например, её язык.
                   Подписи не расталкиваются: у соседних мелких стран и у анклава внутри области они наложатся друг на друга. Лекарство — "display": "auto", тогда плагин скроет каждую подпись, которая перекрылась с уже нарисованной. Но скрытая подпись исчезает совсем, поэтому если так пропадает важное значение (столица, максимум), auto не ставь, а сократи текст подписи через label.
                   Подпись стоит в центре фичи, а у страны с заморскими территориями (Франция) центр уезжает с материка вместе с ними — её значение оставляй цветовой шкале.
                   Названия фич во встроенных картах английские (Brest, Gomel, City of Minsk). Чтобы подписи были русскими, добавляй в строку данных поле label — на карту попадёт именно оно: { "feature": "Minsk", "label": "Минская", "value": 1471 }.
                   Если всё же пишешь свой formatter: название фичи лежит в value.feature.properties.name (в value.feature.name его НЕТ, там undefined), значение — в value.value, а для двух строк возвращай массив строк.
                   На количественной карте обычную легенду датасета убирай: options.plugins.legend.display = false — цветовая шкала её заменяет. На категориальной карте (раздел A4) она, наоборот, нужна — это и есть ключ к цветам.

